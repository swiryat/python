import time

def ask_question(prompt, valid_responses=None):
    """
    Задаёт вопрос и ждёт ответ пользователя.
    Если valid_responses указан, требует ответ из списка.
    """
    while True:
        response = input(prompt + " ").strip().lower()
        if valid_responses:
            if response in valid_responses:
                return response
            else:
                print(f"Пожалуйста, ответь одним из: {', '.join(valid_responses)}")
        else:
            return response

